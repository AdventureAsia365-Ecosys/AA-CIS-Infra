"""AA-853 (S251 D1): the replay baseline (db/replay_baseline/, db/gen_replay_baseline.py) is read by the schema drift
replay only and can never be applied to a real database.

Covered: every committed baseline file carries the marker and opens with the guard; DB Migrate's lint refuses it
whatever its path, and DB Migrate's path rule cannot even select it; the replay sends the guard's setting for baseline
files only and refuses a baseline file without the guard; the decisions file lists exactly the generator's files in
its order; the generator's shape rules (live minus later items, the pre-change CHECK, the key on its index, foreign
keys last, an empty table, recorded hand DDL); `files` order fixes for unregistered legacy files.

Run: python3 -m unittest discover -s db/tests -v
"""
import json
import re
import sys
import tempfile
import unittest
from pathlib import Path

DB = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(DB))

import gen_replay_baseline as gb  # noqa: E402
import replay_migrations as rp  # noqa: E402
import run_migration as rm  # noqa: E402

BASELINE_FILES = sorted((DB / "replay_baseline").glob("*.sql"))


def mig(version, at, desc="x"):
    return {"version": version, "applied_at": at, "description": desc}


class CommittedFiles(unittest.TestCase):
    def test_there_are_baseline_files(self):
        self.assertTrue(BASELINE_FILES)

    def test_each_file_carries_the_marker_and_opens_with_the_guard(self):
        for path in BASELINE_FILES:
            text = path.read_text(encoding="utf-8")
            self.assertTrue(text.startswith(f"-- {rm.BASELINE_MARKER}: "), path.name)
            first = rm.split_statements(text)[0].text
            self.assertIn(gb.GUARD, text, path.name)
            self.assertIn("RAISE EXCEPTION", first, path.name)
            self.assertIn(f"current_setting('{rp.BASELINE_SETTING}', true) IS DISTINCT FROM 'on'", first, path.name)
            self.assertIn(f"IS DISTINCT FROM '{rp.APPLICATION_NAME}'", first, path.name)
            self.assertIn("NOT A MIGRATION", text, path.name)

    def test_guard_names_match_the_replay(self):
        self.assertEqual(gb.GUARD_SETTING, rp.BASELINE_SETTING)
        self.assertEqual(gb.GUARD_APPLICATION, rp.APPLICATION_NAME)
        self.assertEqual(gb.BASELINE_MARKER, rm.BASELINE_MARKER)

    def test_db_migrate_lint_refuses_a_baseline_file_under_any_path(self):
        for path in BASELINE_FILES:
            sql = path.read_text(encoding="utf-8")
            for as_path in (str(path), f"db/migrations/cis/999_{path.stem}.sql", None):
                errors, _ = rm.lint(sql, rm.parse_directives(sql), as_path)
                self.assertTrue(any(rm.BASELINE_MARKER in e for e in errors), (path.name, as_path))

    def test_db_migrate_cannot_select_a_baseline_path(self):
        wf = (DB.parent / ".github" / "workflows" / "db-migrate.yml").read_text(encoding="utf-8")
        rules = [r for r in re.findall(r'\[\[ "\$MIGRATION" =~ (\S+) \]\]', wf) if r.endswith(r"\.sql$")]
        self.assertEqual(len(rules), 1, "db-migrate.yml: expected one .sql path rule")
        rule = re.compile(rules[0])
        self.assertTrue(rule.match("cis/215_publish_log.sql"))
        for path in BASELINE_FILES:
            self.assertIsNone(rule.match(f"replay_baseline/{path.name}"))
            self.assertIsNone(rule.match(f"../replay_baseline/{path.name}"))

    def test_decisions_list_exactly_the_generated_files_in_order(self):
        data = json.loads((DB / "schema_drift_decisions.json").read_text(encoding="utf-8"))
        self.assertEqual([{"file": b["file"], "before": b["before"]} for b in data["baseline"]],
                         gb.decisions_entries())
        self.assertEqual(sorted(b["file"] for b in data["baseline"]),
                         [f"replay_baseline/{p.name}" for p in BASELINE_FILES])
        for b in data["baseline"]:
            self.assertTrue(b.get("reason") and b.get("ref") and b.get("owner"), b)

    def test_titles_and_sources_match_the_spec(self):
        for entry in gb.SPEC:
            text = (DB / entry["file"]).read_text(encoding="utf-8")
            self.assertTrue(text.startswith(f"-- {rm.BASELINE_MARKER}: {entry['title']}\n"), entry["file"])
            self.assertIn("Generated by db/gen_replay_baseline.py", text)


class ReplayReadsItOnlyThere(unittest.TestCase):
    def test_setting_is_sent_first_and_only_by_the_baseline_path(self):
        stmts = rp.baseline_statements("SELECT 1;")
        self.assertEqual(stmts, [f"SET {rp.BASELINE_SETTING} = 'on'", "SELECT 1;"])
        src = (DB / "replay_migrations.py").read_text(encoding="utf-8")
        self.assertEqual(src.count("baseline_statements("), 2)     # its definition and run_item's baseline branch
        self.assertEqual(src.count("SET {BASELINE_SETTING}"), 1)

    def _order(self):
        return rp.plan_order([mig("010", "2026-01-01"), mig("011", "2026-01-02")],
                             {"cis": ["010_a.sql", "011_b.sql", "005_legacy.sql"]})

    def _with_files(self, files: dict, entries: list):
        order = self._order()
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp) / "replay_baseline"
            base.mkdir()
            for name, text in files.items():
                (base / name).write_text(text, encoding="utf-8")
            old = rp.DB_DIR
            rp.DB_DIR = Path(tmp)
            try:
                texts: dict = {}
                problems = rp.add_baseline(order, entries, texts)
            finally:
                rp.DB_DIR = old
        return order, problems, texts

    def test_a_file_without_the_guard_is_refused(self):
        order, problems, texts = self._with_files({"001_x.sql": "CREATE SCHEMA x;"},
                                                  [{"file": "replay_baseline/001_x.sql", "before": "011"}])
        self.assertEqual(len(problems), 1)
        self.assertIn("no replay guard", problems[0])
        self.assertNotIn("baseline", [it.owner for it in order["items"]])

    def test_placed_before_a_key_or_an_unregistered_file(self):
        guarded = f"-- {rm.BASELINE_MARKER}\n{gb.GUARD}\nCREATE SCHEMA x;"
        order, problems, _ = self._with_files(
            {"001_x.sql": guarded, "002_y.sql": guarded},
            [{"file": "replay_baseline/001_x.sql", "before": "cis/005_legacy.sql"},
             {"file": "replay_baseline/002_y.sql", "before": "011"},
             {"file": "replay_baseline/002_y.sql", "before": "cis/404_none.sql"}])
        self.assertEqual(len(problems), 1)
        rels = [it.rel for it in order["items"]]
        self.assertLess(rels.index("baseline/replay_baseline/001_x.sql"), rels.index("cis/005_legacy.sql"))
        self.assertEqual(rels.index("baseline/replay_baseline/002_y.sql") + 1, rels.index("cis/011_b.sql"))


class LegacyOrderFixes(unittest.TestCase):
    LIVE = [mig("030", "2026-05-20"), mig("031", "2026-05-20 01:00"), mig("032", "2026-05-21")]
    SOURCES = {"cis": ["019_social.sql", "021_hitl.sql", "030_audit.sql", "031_s3.sql", "032_harness.sql"]}

    def test_unregistered_files_move_by_rel(self):
        order = rp.plan_order(self.LIVE, self.SOURCES)
        self.assertEqual(order["items"][0].file, "019_social.sql")
        problems = rp.apply_order_fixes(order, [{"files": ["cis/019_social.sql", "cis/021_hitl.sql"],
                                                 "before": "032"}])
        self.assertEqual(problems, [])
        self.assertEqual([it.file for it in order["items"]],
                         ["030_audit.sql", "031_s3.sql", "019_social.sql", "021_hitl.sql", "032_harness.sql"])
        self.assertEqual(order["items"][2].moved_before, "032")

    def test_a_registered_file_cannot_move_by_rel(self):
        order = rp.plan_order(self.LIVE, self.SOURCES)
        before = [it.rel for it in order["items"]]
        problems = rp.apply_order_fixes(order, [{"files": ["cis/030_audit.sql"], "before": "032"}])
        self.assertEqual(len(problems), 1)
        self.assertEqual([it.rel for it in order["items"]], before)


def live_dump():
    return {"generated_at": "2026-10-25T06:15:51+00:00", "relations": {"s": {"t": {
        "columns": [{"name": "id", "type": "uuid", "not_null": True},
                    {"name": "parent", "type": "uuid", "not_null": False},
                    {"name": "status", "type": "text", "not_null": True},
                    {"name": "added_later", "type": "integer", "not_null": False}],
        "constraints": [
            {"constraint": "t_status_check", "type": "c",
             "definition": "CHECK ((status = ANY (ARRAY['a'::text, 'b'::text])))"},
            {"constraint": "t_parent_fkey", "type": "f", "definition": "FOREIGN KEY (parent) REFERENCES s.t(id)"},
            {"constraint": "t_later_check", "type": "c", "definition": "CHECK ((added_later > 0))"}],
        "indexes": [{"index": "t_pkey", "definition": "CREATE UNIQUE INDEX t_pkey ON s.t USING btree (id)",
                     "is_primary": True},
                    {"index": "t_later_idx", "definition": "CREATE INDEX t_later_idx ON s.t USING btree (added_later)",
                     "is_primary": False}]}}}}


class Generator(unittest.TestCase):
    def test_live_table_minus_later_items_with_the_pre_change_check(self):
        obj = {"table": "s.t", "live": True, "why": "w",
               "later_columns": {"added_later": "120"}, "later_indexes": {"t_later_idx": "120"},
               "later_constraints": {"t_later_check": "120"},
               "constraints_before": {"t_status_check": ("CHECK ((status = 'a'::text))", "108")},
               "defaults": {"id": ("gen_random_uuid()", "an INSERT omits it")}}
        sql = "\n".join(gb.table_sql(obj, live_dump()))
        self.assertNotIn("added_later integer", sql)
        self.assertNotIn("CREATE INDEX t_later_idx", sql)
        self.assertNotIn("ADD CONSTRAINT t_later_check", sql)
        self.assertIn("ADD CONSTRAINT t_status_check CHECK ((status = 'a'::text));", sql)
        self.assertIn("id uuid NOT NULL DEFAULT gen_random_uuid()", sql)
        # the key on its own index, before the self-referencing foreign key
        self.assertLess(sql.index("PRIMARY KEY USING INDEX t_pkey"), sql.index("ADD CONSTRAINT t_parent_fkey"))
        self.assertLess(sql.index("CREATE UNIQUE INDEX t_pkey"), sql.index("PRIMARY KEY USING INDEX t_pkey"))

    def test_a_later_column_that_is_not_live_is_an_error(self):
        with self.assertRaises(SystemExit):
            gb.table_sql({"table": "s.t", "live": True, "why": "w", "later_columns": {"nope": "1"}}, live_dump())

    def test_dropped_table_with_only_what_later_files_need(self):
        sql = "\n".join(gb.table_sql({"table": "s.gone", "why": "w", "columns": [("run_id", "uuid NOT NULL", "fk")],
                                      "primary_key": ("gone_pkey", "run_id")}, live_dump()))
        self.assertIn("CREATE TABLE s.gone (\n    run_id uuid NOT NULL\n);", sql)
        self.assertIn("ADD CONSTRAINT gone_pkey PRIMARY KEY USING INDEX gone_pkey;", sql)
        empty = "\n".join(gb.table_sql({"table": "s.empty", "why": "w", "columns": []}, live_dump()))
        self.assertIn("CREATE TABLE s.empty ();", empty)

    def test_render_puts_the_guard_before_the_transaction_and_is_deterministic(self):
        entry = {"file": "replay_baseline/009_t.sql", "before": "107", "lead": "Lead.", "title": "T",
                 "objects": [{"schema": "x", "why": "w"}, {"sql": ["DROP TABLE x.y;"], "why": "archived script"}]}
        text = gb.render(entry, live_dump())
        self.assertEqual(text, gb.render(entry, live_dump()))
        self.assertLess(text.index(gb.GUARD), text.index("BEGIN;"))
        self.assertIn("CREATE SCHEMA x;", text)
        self.assertIn("DROP TABLE x.y;", text)
        self.assertTrue(text.rstrip().endswith("COMMIT;"))
        self.assertIn("2026-10-25T06:15:51+00:00", text)


