"""AA-1038 R5 slice 3 (root ADR 0019 d11, root contract lead.submitted.v1): offline guards for the lead channels' infra.

1. The aa-m2m pool has the resource server tripplanner.leads with the one scope deliver, and the CRM client (the
   pool's only client) gets it; no other client exists that could take it.
2. The CRM task (API + in-process worker) carries TRIPPLANNER_API_URL built from the TripPlanner HTTP API resource
   (no literal host, no account id, lower-case origin without a trailing slash: the CRM refuses to start otherwise).
3. Secret tripplanner/<env>/lead-webhook-key is generated by Terraform without entering state (ephemeral
   random_password -> write-only version), its ARN is on the plan refresh list, and only the two delivering TripPlanner
   roles (browse + assembly execution role, jobs role) are granted it.
4. TP_LEAD_EMAIL_FROM = var.ses_from_address on assembly and jobs (not browse), and both roles carry the shared SES send
   grant pinned to that From address (no new identity).
5. The assembly Lambda pins the M2M issuer + CRM client from the pool and turns the CRM pull on in Terraform.

Run: python3 -m pytest -q tools/terraform/tests/test_aa1038_leads_infra.py
"""
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
AA365 = ROOT / "accounts" / "aa365"
ENV = ROOT / "modules" / "environment"
M2M = (AA365 / "identity_m2m.tf").read_text(encoding="utf-8")
SES = (AA365 / "ses.tf").read_text(encoding="utf-8")
CICD_SPLIT = (AA365 / "cicd_split.tf").read_text(encoding="utf-8")
TP = (ENV / "tripplanner.tf").read_text(encoding="utf-8")
TP_JOBS = (ENV / "tripplanner_jobs.tf").read_text(encoding="utf-8")
TP_OUT = (ENV / "tripplanner_outputs.tf").read_text(encoding="utf-8")
CRM_APP = (ENV / "crm_app.tf").read_text(encoding="utf-8")

SECRET = "aws_secretsmanager_secret.tripplanner_lead_webhook_key"


def _block(text: str, header: str) -> str:
    """The brace-balanced block that follows ``header`` (a resource / output / data line)."""
    start = text.index(header)
    i = text.index("{", start)
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return text[i: j + 1]
    raise AssertionError(f"unbalanced block after {header}")


def _all_tf() -> dict[str, str]:
    out = {}
    for d in (AA365, ROOT / "modules"):
        for f in sorted(d.rglob("*.tf")):
            out[str(f.relative_to(ROOT))] = f.read_text(encoding="utf-8")
    return out


class M2mResourceServer(unittest.TestCase):
    def test_tripplanner_leads_server_has_only_deliver(self) -> None:
        self.assertRegex(M2M, r'idm2m_tripplanner_identifier\s*=\s*"tripplanner\.leads"')
        scopes = re.search(r"idm2m_tripplanner_scopes\s*=\s*\{(.*?)\n  \}", M2M, re.S)
        assert scopes, "idm2m_tripplanner_scopes not found"
        self.assertEqual(re.findall(r"^\s*([a-z_]+)\s*=", scopes.group(1), re.M), ["deliver"])
        server = _block(M2M, 'resource "aws_cognito_resource_server" "tripplanner_leads"')
        self.assertIn("identifier   = local.idm2m_tripplanner_identifier", server)
        self.assertIn("user_pool_id = aws_cognito_user_pool.m2m.id", server)
        self.assertIn("for_each = local.idm2m_tripplanner_scopes", server)

    def test_granted_to_the_crm_client(self) -> None:
        client = _block(M2M, 'resource "aws_cognito_user_pool_client" "m2m_crm"')
        self.assertIn("aws_cognito_resource_server.tripplanner_leads.scope_identifiers", client)
        self.assertIn('allowed_oauth_flows                  = ["client_credentials"]', client)

    def test_the_crm_client_is_the_pools_only_client(self) -> None:
        # Least privilege holds only while no other client of the pool exists anywhere in the code.
        clients = []
        for name, text in _all_tf().items():
            for m in re.finditer(r'^resource "aws_cognito_user_pool_client" "([a-z0-9_]+)"', text, re.M):
                body = _block(text, m.group(0))
                if "aws_cognito_user_pool.m2m.id" in body:
                    clients.append(f"{name}:{m.group(1)}")
        self.assertEqual(clients, ["accounts/aa365/identity_m2m.tf:m2m_crm"])

    def test_scope_output(self) -> None:
        out = _block(M2M, 'output "identity_m2m_tripplanner_scopes"')
        self.assertIn("aws_cognito_resource_server.tripplanner_leads.scope_identifiers", out)


class CrmTaskTripplannerUrl(unittest.TestCase):
    def test_env_from_the_http_api_resource(self) -> None:
        task = _block(CRM_APP, 'resource "aws_ecs_task_definition" "crm_api"')
        m = re.search(r'\{ name = "TRIPPLANNER_API_URL", value = (.+) \},', task)
        assert m, "TRIPPLANNER_API_URL missing from the CRM task environment"
        self.assertEqual(m.group(1), 'lower(trimsuffix(aws_apigatewayv2_api.tripplanner.api_endpoint, "/"))')

    def test_set_once(self) -> None:
        self.assertEqual(len(re.findall(r'name = "TRIPPLANNER_API_URL"', CRM_APP)), 1)


class LeadWebhookKeySecret(unittest.TestCase):
    def test_name_and_tags(self) -> None:
        secret = _block(TP, f'resource "aws_secretsmanager_secret" "tripplanner_lead_webhook_key"')
        self.assertIn('name                    = "tripplanner/${var.environment}/lead-webhook-key"', secret)
        self.assertIn('DataClassification = "restricted"', secret)
        self.assertIn("local.tp_tags", secret)

    def test_value_generated_and_never_in_state(self) -> None:
        self.assertRegex(TP, r'(?m)^ephemeral "random_password" "tripplanner_lead_webhook_key" \{')
        self.assertNotRegex(TP, r'(?m)^resource "random_password" "tripplanner_lead_webhook_key"')
        version = _block(TP, 'resource "aws_secretsmanager_secret_version" "tripplanner_lead_webhook_key"')
        self.assertIn(f"secret_id                = {SECRET}.id", version)
        self.assertIn("secret_string_wo         = ephemeral.random_password.tripplanner_lead_webhook_key.result", version)
        self.assertIn("secret_string_wo_version = local.tp_lead_webhook_key_version", version)
        self.assertNotRegex(version, r"(?m)^\s*secret_string\s*=")

    def test_on_the_plan_refresh_list(self) -> None:
        out = _block(TP_OUT, 'output "tripplanner_lead_webhook_key_secret_arn"')
        self.assertIn(f"value       = {SECRET}.arn", out)
        start = CICD_SPLIT.index("tf_plan_secret_arns = concat(")
        self.assertIn("module.environment.tripplanner_lead_webhook_key_secret_arn",
                      CICD_SPLIT[start: CICD_SPLIT.index("\n  )", start)])

    def test_only_the_two_delivering_roles_are_granted(self) -> None:
        holders = []
        for name, text in _all_tf().items():
            for m in re.finditer(rf"{re.escape(SECRET)}\.arn", text):
                line = text[text.rfind("\n", 0, m.start()) + 1: text.find("\n", m.end())]
                if "Resource" in line or "resources" in line:
                    holders.append(name)
        self.assertEqual(sorted(holders), ["modules/environment/tripplanner.tf", "modules/environment/tripplanner_jobs.tf"])
        exec_policy = _block(TP, 'resource "aws_iam_role_policy" "tripplanner_lambda_permissions"')
        jobs_policy = _block(TP_JOBS, 'resource "aws_iam_role_policy" "tripplanner_jobs_permissions"')
        for policy in (exec_policy, jobs_policy):
            stmt = re.search(r'Sid\s*=\s*"ReadLeadWebhookKeySecret"(.*?)\}', policy, re.S)
            assert stmt, "ReadLeadWebhookKeySecret missing"
            self.assertIn('Action   = ["secretsmanager:GetSecretValue"]', stmt.group(1))
            self.assertIn(f"Resource = [{SECRET}.arn]", stmt.group(1))


def _lambda_env(text: str, name: str) -> str:
    fn = _block(text, f'resource "aws_lambda_function" "{name}"')
    return _block(fn, "variables = {")


class LeadEmailAndCrmPull(unittest.TestCase):
    def test_email_from_on_assembly_and_jobs_only(self) -> None:
        self.assertRegex(_lambda_env(TP, "tripplanner_assembly"), r"TP_LEAD_EMAIL_FROM\s*=\s*var\.ses_from_address")
        self.assertRegex(_lambda_env(TP_JOBS, "tripplanner_jobs"), r"TP_LEAD_EMAIL_FROM\s*=\s*var\.ses_from_address")
        self.assertNotIn("TP_LEAD_", _lambda_env(TP, "tripplanner_browse"))

    def test_both_roles_send_only_as_the_shared_from(self) -> None:
        exec_grant = _block(SES, 'resource "aws_iam_role_policy" "tripplanner_lambda_ses_send"')
        jobs_grant = _block(SES, 'resource "aws_iam_role_policy" "tripplanner_jobs_ses_send"')
        self.assertIn("role   = module.environment.tripplanner_lambda_exec_role_id", exec_grant)
        self.assertIn("role   = module.environment.tripplanner_jobs_exec_role_id", jobs_grant)
        for grant in (exec_grant, jobs_grant):
            self.assertIn("policy = data.aws_iam_policy_document.ses_send.json", grant)
        doc = _block(SES, 'data "aws_iam_policy_document" "ses_send"')
        self.assertIn('variable = "ses:FromAddress"', doc)
        self.assertIn("values   = [var.ses_from_address]", doc)
        self.assertEqual(len(re.findall(r'^resource "aws_sesv2_email_identity"', SES, re.M)), 1)
        out = _block(TP_OUT, 'output "tripplanner_jobs_exec_role_id"')
        self.assertIn("aws_iam_role.tripplanner_jobs_exec.id", out)

    def test_assembly_m2m_pins_and_crm_switch(self) -> None:
        env = _lambda_env(TP, "tripplanner_assembly")
        self.assertRegex(env, r'TP_M2M_ISSUER\s*=\s*"https://\$\{var\.m2m_pool_endpoint\}"')
        self.assertRegex(env, r"TP_M2M_CRM_CLIENT_ID\s*=\s*var\.m2m_crm_client_id")
        self.assertRegex(env, r'TP_LEAD_CRM_PULL_ENABLED\s*=\s*"true"')
        self.assertNotIn("TP_M2M_", _lambda_env(TP_JOBS, "tripplanner_jobs"))


if __name__ == "__main__":
    unittest.main()
