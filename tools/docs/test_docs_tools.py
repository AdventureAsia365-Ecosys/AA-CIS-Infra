"""Unit tests for the docs lint tools (AA-888). Run: python -m unittest discover -s tools/docs -p 'test_*.py'.

Each check gets one passing and one failing fixture, so a change to a regex that silently stops
catching (or starts flagging everything) fails CI. The Done-when of AA-888 asks that a PR adding an
`sg-` ID or a backslash-continued `aws` command fails; these fixtures pin that behaviour.

The same files run in AA-Ecosys, AA-Booking and AA-CIS-Infra (tools/docs/README.md). The public repos
scan every tracked file for literal resource IDs (AA-902), so the fake IDs below are assembled at run
time and never appear whole in this file.
"""

