class TempRepo(unittest.TestCase):
    def setUp(self) -> None:
        self.root = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.root)

    def write(self, rel: str, text: str) -> None:
        p = self.root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(textwrap.dedent(text), encoding="utf-8")

    def run_quiet(self, fn, *args):
        with contextlib.redirect_stdout(io.StringIO()):
            return fn(*args)


class AwsMultilineTest(TempRepo):
    def test_backslash_continuation_fails(self) -> None:
        self.write("docs/ops/x.md", "```bash\naws ecs update-service --cluster c \\\n  --service s\n```\n")
        self.write("skill/s/SKILL.md", "URL=$(aws s3 presign s3://b/k \\\n  --expires-in 300)\n")
        found = check_docs_text.check_aws_multiline(self.root, ["docs/ops/x.md", "skill/s/SKILL.md"])
        self.assertEqual([(f.path, f.line) for f in found], [("docs/ops/x.md", 2), ("skill/s/SKILL.md", 1)])

    def test_single_line_and_other_tools_pass(self) -> None:
        self.write("docs/ops/x.md", textwrap.dedent("""\
            aws ecs list-tasks --cluster c --profile aa365-admin --region us-west-1
            docker run --rm \\
              image
            Use the AWS console. \\
            aws s3 ls s3://b/ \\  docs-lint: ignore
            """))
        self.assertEqual(check_docs_text.check_aws_multiline(self.root, ["docs/ops/x.md"]), [])

    def test_journals_are_out_of_scope(self) -> None:
        self.write("docs/sessions/2026-01-01-x.md", "aws ecs update-service \\\n  --x\n")
        self.write("docs/ops/y.md", "ok\n")
        files = check_docs_text._select(self.root, check_docs_text.AWS_SCOPE, [])
        self.assertEqual(files, ["docs/ops/y.md"])


class ResourceIdTest(TempRepo):
    def ids(self, line: str) -> list[str]:
        self.write("docs/ops/x.md", line + "\n")
        return [f.message.split("'")[1] for f in check_docs_text.check_resource_ids(self.root, ["docs/ops/x.md"])]

    def test_flags_literal_ids(self) -> None:
        self.assertEqual(self.ids(f"Open {SG} on 5432."), [SG])
        self.assertEqual(self.ids(SUBNET), [SUBNET])
        self.assertEqual(self.ids("Account 123456789012 owns it."), ["123456789012"])
        self.assertEqual(self.ids("arn:aws:iam::123456789012:role/x"), ["arn:aws:iam::123456789012:"])
        self.assertEqual(self.ids(f"pool {POOL}"), [POOL])
        self.assertEqual(self.ids(f"https://{APIGW}us-west-1.amazonaws.com"), [APIGW])

    def test_names_and_conventions_pass(self) -> None:
        self.assertEqual(self.ids("Bucket aa-cis-bronze-123456789012 and aa-cis-api-sg."), [])
        self.assertEqual(self.ids("Run 20261019123045 at 2026-10-19; sg-xyz is a name."), [])
        self.assertEqual(self.ids(f"{SG} <!-- docs-lint: ignore -->"), [])

    def test_exempt_and_generated_files_are_skipped(self) -> None:
        self.write("docs/onboarding.md", "| acc2 | 123456789012 |\n")
        self.write("docs/gen.md", f"<!-- GENERATED by x from y@z - do not edit -->\n{SG}\n")
        found = check_docs_text.check_resource_ids(self.root, ["docs/onboarding.md", "docs/gen.md"])
        self.assertEqual(found, [])

    def test_warn_mode_exits_zero_error_mode_exits_one(self) -> None:
        self.write("docs/ops/x.md", f"{SG}\n")
        args = ["resource-ids", "docs/ops/x.md", "--root", str(self.root)]
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            self.assertEqual(check_docs_text.main(args + ["--mode", "warn"]), 0)
        self.assertTrue(out.getvalue().startswith("::warning file=docs/ops/x.md,line=1,"))  # GitHub's level name
        self.assertEqual(self.run_quiet(check_docs_text.main, args + ["--mode", "error"]), 1)

    def test_block_keeps_chosen_kinds_failing_in_warn_mode(self) -> None:
        # Infra (private): VPC IDs and API Gateway hosts fail, ARNs and account IDs only warn.
        self.write("docs/ops/arn.md", "arn:aws:iam::123456789012:role/x\n")
        self.write("docs/ops/sg.md", f"{SG}\n")
        block = ["--mode", "warn", "--block", "vpc,apigw", "--root", str(self.root)]
        self.assertEqual(self.run_quiet(check_docs_text.main, ["resource-ids", "docs/ops/arn.md"] + block), 0)
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            self.assertEqual(check_docs_text.main(["resource-ids", "docs/ops/sg.md"] + block), 1)
        self.assertTrue(out.getvalue().startswith("::error file=docs/ops/sg.md,line=1,"))
        with contextlib.redirect_stderr(io.StringIO()), self.assertRaises(SystemExit):
            check_docs_text.main(["resource-ids", "--block", "sgs", "--root", str(self.root)])


class AllMarkdownScopeTest(TempRepo):
    def test_all_scans_root_pages_and_skips_journals(self) -> None:
        # App and Infra repos keep pages at the root (README.md, CONTEXT.md), outside the default scope.
        self.write("README.md", "aws s3 sync dist s3://b/k \\\n  --delete\n")
        self.write("backend/README.md", "ok\n")
        self.write("docs/implementation-notes/AA-1.md", "aws s3 ls \\\n")
        args = ["aws-multiline", "--root", str(self.root)]
        self.assertEqual(self.run_quiet(check_docs_text.main, args), 0)  # default scope: docs, skill, ...
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            self.assertEqual(check_docs_text.main(args + ["--all"]), 1)
        self.assertIn("::error file=README.md,line=1,", out.getvalue())
        self.assertNotIn("implementation-notes", out.getvalue())
        self.assertIn("aws-multiline: 2 files checked, 1 errors", out.getvalue())


class AdrIndexTest(TempRepo):
    def test_valid_index_passes(self) -> None:
        self.write("docs/adr/0001-a.md", "# A\n\n- **Status:** Accepted (01/10/2026, S200).\n")
        self.write("docs/adr/0002-b.md", "---\nstatus: proposed\n---\n\n# B\n")
        self.write("docs/adr/0003-c.md", "# C\n\n## Status\n\n**Superseded** by 0004.\n")
        self.write("docs/adr/README.md", "[0001](0001-a.md) [0002](0002-b.md) [0003](0003-c.md)\n")
        self.assertEqual(check_adr_index.check(self.root / "docs/adr", self.root), [])

    def test_missing_status_bad_status_and_unlisted_adr_fail(self) -> None:
        self.write("docs/adr/0001-a.md", "# A\n\nNo status here.\n")
        self.write("docs/adr/0002-b.md", "# B\n\n- **Status:** Maybe later\n")
        self.write("docs/adr/README.md", "[0001](0001-a.md)\n")
        titles = sorted(f.title + ":" + f.path for f in check_adr_index.check(self.root / "docs/adr", self.root))
        self.assertEqual(titles, ["ADR index:docs/adr/README.md", "ADR status:docs/adr/0001-a.md",
                                  "ADR status:docs/adr/0002-b.md"])


